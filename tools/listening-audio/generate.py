"""Records the Listening scripts with Kokoro TTS into chrome-extension/practice/audio/<key>.mp3.

Only lines without a file are recorded, files no line uses any more are deleted, and audio/have.js lists what exists.
Setup (once): pip install kokoro-onnx==0.4.9 soundfile, ffmpeg on PATH, and kokoro-v1.0.onnx + voices-v1.0.bin from
https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0 in a folder passed as the first argument.
Run:  node tools/listening-audio/lines.js > jobs.json && python tools/listening-audio/generate.py <model-folder> jobs.json
"""
import json, os, subprocess, sys, tempfile, time
import soundfile as sf
from kokoro_onnx import Kokoro

SPEED = 0.95   # a touch slower than Kokoro's default: clearer, still natural
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'chrome-extension', 'practice', 'audio')

def main(model_dir, jobs_path):
    jobs = json.load(open(jobs_path, encoding='utf-8'))
    os.makedirs(OUT, exist_ok=True)
    todo = [j for j in jobs if not os.path.exists(os.path.join(OUT, j['key'] + '.mp3'))]
    print(f'{len(jobs)} lines, {len(todo)} to record', flush=True)
    k = Kokoro(os.path.join(model_dir, 'kokoro-v1.0.onnx'), os.path.join(model_dir, 'voices-v1.0.bin')) if todo else None
    t0 = time.time()
    for i, j in enumerate(todo, 1):
        audio, sr = k.create(j['text'], voice=j['voice'], speed=SPEED, lang='en-gb' if j['voice'][0] == 'b' else 'en-us')
        with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as w:
            sf.write(w.name, audio, sr)
        mp3 = os.path.join(OUT, j['key'] + '.mp3')
        # Mono 32 kbps MP3: plays everywhere, about 240 KB per minute of speech
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', w.name, '-ac', '1', '-b:a', '32k', mp3 + '.tmp.mp3'], check=True)
        os.replace(mp3 + '.tmp.mp3', mp3); os.unlink(w.name)
        if i % 25 == 0 or i == len(todo):
            print(f'  {i}/{len(todo)}  {time.time() - t0:.0f}s', flush=True)
    keep = {j['key'] for j in jobs}
    for f in os.listdir(OUT):
        if f.endswith('.mp3') and f[:-4] not in keep:
            os.unlink(os.path.join(OUT, f)); print('removed unused', f)
    have = sorted(f[:-4] for f in os.listdir(OUT) if f.endswith('.mp3'))
    with open(os.path.join(OUT, 'have.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/listening-audio/generate.py: the recorded lines in this folder.\n')
        f.write(f"window.LISTEN_AUDIO_HAVE = '{' '.join(have)}';\n")
    print(f'have.js: {len(have)} recordings')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
